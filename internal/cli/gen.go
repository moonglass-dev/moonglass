package cli

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"moonglass.dev/moonglass/internal/registry"
)

// Generate renders generated.go from the registry's operations. A subcommand
// is the operation name with dots turned into spaces.
func Generate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by \"make generate\" from internal/registry; DO NOT EDIT.\n\npackage cli\n\nvar generated = []command{\n")
	for _, s := range registry.Operations() {
		fmt.Fprintf(&b, "\t{Name: %s, Method: %s, Path: %s, Summary: %s},\n",
			strconv.Quote(strings.ReplaceAll(s.Name, ".", " ")), strconv.Quote(s.Method), strconv.Quote(s.Path), strconv.Quote(s.Summary))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated CLI: %w", err)
	}
	return out, nil
}
