package cli

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"strconv"
	"strings"

	"moonglass.dev/moonglass/internal/registry"
)

// kindNames is how a flag kind is written into generated.go.
var kindNames = [...]string{kindString: "kindString", kindBool: "kindBool", kindInt: "kindInt", kindList: "kindList"}

// Generate renders generated.go from ops, skipping every operation whose
// subcommand is on local. A subcommand is the operation name with dots turned
// into spaces.
func Generate(ops []registry.Declaration, local []registry.LocalCommand) ([]byte, error) {
	cmds, err := commands(ops, local)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by \"make generate\" from internal/registry; DO NOT EDIT.\n\npackage cli\n\nvar generated = []command{\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "\t{Name: %s, Method: %s, Path: %s, Summary: %s",
			strconv.Quote(c.Name), strconv.Quote(c.Method), strconv.Quote(c.Path), strconv.Quote(c.Summary))
		if len(c.Inputs) != 0 {
			b.WriteString(", Inputs: []input{")
			for i, in := range c.Inputs {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "{Flag: %s, JSON: %s, Kind: %s, Required: %t, Doc: %s}",
					strconv.Quote(in.Flag), strconv.Quote(in.JSON), kindNames[in.Kind], in.Required, strconv.Quote(in.Doc))
			}
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated CLI: %w", err)
	}
	return out, nil
}

// commands derives one command per operation, except ones whose subcommand is a
// local command: those run on this machine and generate nothing.
func commands(ops []registry.Declaration, local []registry.LocalCommand) ([]command, error) {
	localNames := make(map[string]bool, len(local))
	for _, l := range local {
		localNames[l.Name] = true
	}
	cmds := make([]command, 0, len(ops))
	for _, d := range ops {
		name := strings.ReplaceAll(d.Name, ".", " ")
		if localNames[name] {
			continue
		}
		ins, err := inputs(d)
		if err != nil {
			return nil, err
		}
		cmds = append(cmds, command{Name: name, Method: d.Method, Path: d.Path, Summary: d.Summary, Inputs: ins})
	}
	return cmds, nil
}

// inputs derives one flag per exported field of the operation's In, in field
// order.
func inputs(d registry.Declaration) ([]input, error) {
	if d.In == nil || d.In.Kind() != reflect.Struct {
		return nil, fmt.Errorf("operation %s: In must be a struct type", d.Name)
	}
	ins := make([]input, 0, d.In.NumField())
	for i := range d.In.NumField() {
		f := d.In.Field(i)
		if !f.IsExported() {
			continue
		}
		name, opts, _ := strings.Cut(f.Tag.Get("json"), ",")
		if name == "" || name == "-" {
			return nil, fmt.Errorf("operation %s: input field %s has no json name: give it a snake_case json tag", d.Name, f.Name)
		}
		kind, ok := inputKind(f.Type)
		if !ok {
			return nil, fmt.Errorf("operation %s: input field %s (json %q) is a %s, which has no flag: use string, bool, int64 or []string, or add the subcommand %q to registry.LocalCommands",
				d.Name, f.Name, name, f.Type, strings.ReplaceAll(d.Name, ".", " "))
		}
		ins = append(ins, input{
			Flag:     flagName(name),
			JSON:     name,
			Doc:      f.Tag.Get("doc"),
			Kind:     kind,
			Required: !strings.Contains(","+opts+",", ",omitempty,"),
		})
	}
	return ins, nil
}

// flagName is the flag for a json name: env for environment, otherwise the name
// with underscores turned into hyphens.
func flagName(name string) string {
	if name == "environment" {
		return "env"
	}
	return strings.ReplaceAll(name, "_", "-")
}

// inputKind names the flag kind of a field type, or false when it has none.
func inputKind(t reflect.Type) (flagKind, bool) {
	if t.Kind() == reflect.String {
		return kindString, true
	}
	if t.Kind() == reflect.Bool {
		return kindBool, true
	}
	if t.Kind() == reflect.Int64 {
		return kindInt, true
	}
	if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.String {
		return kindList, true
	}
	return 0, false
}
